CREATE TABLE address (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    street      VARCHAR(255)             NOT NULL,
    city        VARCHAR(100)             NOT NULL,
    state       VARCHAR(100)             NOT NULL,
    pin_code    VARCHAR(6)               NOT NULL,
    version     BIGINT                   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE bank (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_name    VARCHAR(150)             NOT NULL,
    ifsc_code    VARCHAR(11)              NOT NULL,
    branch_name  VARCHAR(150)             NOT NULL,
    address_id   BIGINT                   NOT NULL,
    version      BIGINT                   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_bank_ifsc_code UNIQUE (ifsc_code),
    CONSTRAINT uk_bank_address UNIQUE (address_id),
    CONSTRAINT fk_bank_address FOREIGN KEY (address_id) REFERENCES address (id)
);

CREATE TABLE account (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number      VARCHAR(20)              NOT NULL,
    account_holder_name VARCHAR(150)             NOT NULL,
    balance             NUMERIC(19, 2)           NOT NULL,
    account_type        VARCHAR(20)              NOT NULL,
    bank_id             BIGINT                   NOT NULL,
    version             BIGINT                   NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_account_number UNIQUE (account_number),
    CONSTRAINT fk_account_bank FOREIGN KEY (bank_id) REFERENCES bank (id),
    CONSTRAINT ck_account_balance_non_negative CHECK (balance >= 0)
);

CREATE INDEX idx_account_bank_id ON account (bank_id);
